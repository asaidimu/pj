#!/bin/sh
# src/completion/generate.sh - generate shell completions for pj
#
# Reads the "# summary" and "# completion:" tags from every module's
# index.sh (core modules + user plugins) and emits a completion script
# for the requested shell on stdout.
#
#   "# completion:" values:
#     none          no operand completion (default)
#     projects      complete project names (pj list)
#     recipes       complete recipe names (pj new help)
#     analysis      complete for analyze/commit/document style commands
#
# Usage:
#   sh generate.sh [zsh|bash]    # default zsh
#
# Env:
#   FRAMEWORK_NAME  default: pj
#   FRAMEWORK_PATH  required - framework install location
#   FRAMEWORK_ROUTE default: $FRAMEWORK_PATH/src/module
#   CUSTOM_PLUGINS_PATH default: $HOME/.config/$FRAMEWORK_NAME/plugins

set -u

FRAMEWORK_NAME="${FRAMEWORK_NAME:-pj}"
FRAMEWORK_PATH="${FRAMEWORK_PATH:?FRAMEWORK_PATH must be set}"
FRAMEWORK_ROUTE="${FRAMEWORK_ROUTE:-$FRAMEWORK_PATH/src/module}"
CUSTOM_PLUGINS_PATH="${CUSTOM_PLUGINS_PATH:-$HOME/.config/$FRAMEWORK_NAME/plugins}"

TARGET="${1:-zsh}"

TEMPDIR="${TMPDIR:-/tmp}"
MODULES_FILE="$TEMPDIR/pj-completion-$$"
trap 'rm -f "$MODULES_FILE"' 0

# -- collection ---------------------------------------------------------------

# one awk per module: anchored tag parse (colons in a summary survive,
# unlike the old greedy sed), no grep/sed/head/tr pipeline
collect_modules() {
  for route in "$FRAMEWORK_ROUTE" "$CUSTOM_PLUGINS_PATH"; do
    [ -d "$route" ] || continue
    for module in "$route"/*; do
      [ -d "$module" ] || continue
      index="$module/index.sh"
      [ -f "$index" ] || continue

      name="${module##*/}"
      awk -v name="$name" -v fallback="see $FRAMEWORK_NAME $name help" '
        /^# *summary:/ && !sum { sub(/^# *summary: */, ""); sum = $0 }
        /^# *completion:/ && !cmp { sub(/^# *completion: */, ""); cmp = $0 }
        END {
          if (sum == "") sum = fallback
          if (cmp == "") cmp = "none"
          # colons and quotes would break the record format and _describe
          gsub(/["`:]/, "", sum)
          gsub("\047", "", sum)
          printf "%s:%s:%s\n", name, sum, cmp
        }
      ' "$index"
    done
  done
}

# build group strings (name joined by |) per completion type; skips help.
# leaf (no operand completion) is only needed by bash, whose empty case
# arm keeps those commands from falling through to the command list.
build_groups() {
  projects=""
  recipes=""
  analysis=""
  leaf=""
  while IFS=: read -r name summary completion; do
    [ -z "$name" ] && continue
    [ "$name" = "help" ] && continue
    case "$completion" in
      projects) projects="${projects:+$projects|}$name" ;;
      recipes) recipes="${recipes:+$recipes|}$name" ;;
      analysis) analysis="${analysis:+$analysis|}$name" ;;
      *) leaf="${leaf:+$leaf|}$name" ;;
    esac
  done < "$MODULES_FILE"
}

# -- zsh ---------------------------------------------------------------------

emit_zsh() {
cat <<'ZHEAD'
#compdef pj

# Zsh completion for pj command
# Generated by src/completion/generate.sh - do not edit

_pj() {
    local context state line
    typeset -A opt_args

    # Main command structure
    _arguments -C \
        '(-v --version)'{-v,--version}'[show command version]' \
        '1: :_pj_commands' \
        '*:: :->args' && return 0

    case $state in
        args)
            case $words[1] in
                help)
                    _pj_help_completion
                    ;;
ZHEAD
  build_groups
  [ -n "$projects" ] && \
    printf '                %s)\n                    _pj_project_completion\n                    ;;\n' "$projects"
  [ -n "$recipes" ] && \
    printf '                %s)\n                    _pj_new_completion\n                    ;;\n' "$recipes"
  [ -n "$analysis" ] && \
    printf '                %s)\n                    _pj_project_analysis_completion\n                    ;;\n' "$analysis"
  cat <<'ZMID'
                *)
                    # Check if the command supports help
                    if [[ $words[-1] == "help" ]]; then
                        return 0
                    fi
                    ;;
            esac
            ;;
    esac

    return 1
}

# Complete main commands
_pj_commands() {
    local -a commands
    commands=(
ZMID
  while IFS=: read -r name summary completion; do
    printf "        '%s:%s'\n" "$name" "$summary"
  done < "$MODULES_FILE"
  cat <<'ZCMD'
    )
    _describe 'commands' commands
}

# Complete help subcommands
_pj_help_completion() {
    local -a help_commands
    help_commands=(
ZCMD
  while IFS=: read -r name summary completion; do
    printf "        '%s:show help for %s command'\n" "$name" "$name"
  done < "$MODULES_FILE"
  cat <<'ZHELP'
    )
    _describe 'help commands' help_commands
}

# Project names straight from the projects directory — same thing
# `pj list` shows, without booting the framework on every TAB.
# Export PROJECTS_PATH in your shell if you override it in env.sh.
_pj_get_projects() {
    local dir="${PROJECTS_PATH:-$HOME/projects}"
    local -a projects
    [[ -d $dir ]] || return 0
    projects=(${(f)"$(command ls -1 "$dir" 2>/dev/null)"})
    if [[ ${#projects[@]} -gt 0 ]]; then
        printf '%s\n' "${projects[@]}"
    fi
}

# Recipe names via the machine-readable `pj new --names`
_pj_get_recipes() {
    local -a recipes
    recipes=(${(f)"$(command pj new --names 2>/dev/null)"})
    if [[ ${#recipes[@]} -gt 0 ]]; then
        printf '%s\n' "${recipes[@]}"
    fi
}

# Complete project names for commands that operate on projects
_pj_project_completion() {
    local -a projects
    projects=(${(f)"$(_pj_get_projects)"})

    if [[ ${#projects[@]} -gt 0 ]]; then
        _describe 'projects' projects
    else
        _message 'no projects found (run pj refresh?)'
    fi

    # Also allow help completion
    if [[ $words[-1] != "help" ]]; then
        _arguments \
            ':: :->help_option'
        case $state in
            help_option)
                _values 'help' 'help[show command help]'
                ;;
        esac
    fi
}

# Complete for project analysis commands (analyze, commit, document)
_pj_project_analysis_completion() {
    # These might work on current directory or specific projects
    # For now, just allow help completion
    if [[ $words[-1] != "help" ]]; then
        _arguments \
            ':: :->help_option'
        case $state in
            help_option)
                _values 'help' 'help[show command help]'
                ;;
        esac
    fi
}

# Complete pj new command with recipes and options
_pj_new_completion() {
    local -a recipes

    # Get available recipes dynamically
    recipes=(${(f)"$(_pj_get_recipes)"})

    # Handle different positions in the command
    case $CURRENT in
        2)
            # First argument: recipe name
            if [[ ${#recipes[@]} -gt 0 ]]; then
                _describe 'recipes' recipes
            else
                _message 'no recipes available (run pj new help to see recipes)'
            fi
            ;;
        3)
            # Second argument: project name (free text)
            _message 'project name'
            ;;
        *)
            # Additional arguments: flags or help
            _arguments \
                '(-o --overwrite)'{-o,--overwrite}'[overwrite project]' \
                ':: :->help_option'
            case $state in
                help_option)
                    if [[ $words[-1] != "help" ]]; then
                        _values 'help' 'help[show command help]'
                    fi
                    ;;
            esac
            ;;
    esac
}

# Initialize completion
_pj "$@"
ZHELP
}

# -- bash --------------------------------------------------------------------

emit_bash() {
cat <<'BHEAD'
# bash completion for pj
# Generated by src/completion/generate.sh - do not edit

_pj() {
    local cur
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"

    local commands
    commands="
BHEAD
  _first=1
  while IFS=: read -r name summary completion; do
    [ -z "$name" ] && continue
    if [ "$_first" -eq 1 ]; then
      printf '%s' "$name"
      _first=0
    else
      printf ' %s' "$name"
    fi
  done < "$MODULES_FILE"
  printf '\n    "\n'
  cat <<'BMID'

    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
        return 0
    fi

    case "${COMP_WORDS[1]}" in
        help)
            COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
            ;;
BMID
  build_groups
  [ -n "$projects" ] && \
    printf '        %s)\n            _pj_complete_projects\n            ;;\n' "$projects"
  [ -n "$recipes" ] && \
    printf '        %s)\n            _pj_complete_recipes\n            ;;\n' "$recipes"
  [ -n "$analysis" ] && \
    printf '        %s)\n            COMPREPLY=( $(compgen -W "help" -- "$cur") )\n            ;;\n' "$analysis"
  [ -n "$leaf" ] && \
    printf '        %s)\n            ;;\n' "$leaf"
  cat <<'BTAIL'
        *)
            COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
            ;;
    esac
}

# Complete project names for commands that operate on projects
_pj_complete_projects() {
    local cur="${COMP_WORDS[COMP_CWORD]}"
    local dir="${PROJECTS_PATH:-$HOME/projects}"
    local IFS=$'\n'
    COMPREPLY=( $(compgen -W "$(command ls -1 "$dir" 2>/dev/null)" -- "$cur") )
}

# Complete recipe names for pj new
_pj_complete_recipes() {
    local cur="${COMP_WORDS[COMP_CWORD]}"
    COMPREPLY=( $(compgen -W "$(command pj new --names 2>/dev/null)" -- "$cur") )
}

complete -F _pj pj
BTAIL
}

# -- main ---------------------------------------------------------------------

# user plugins override core modules of the same name: keep the last line
# per name, then sort for stable, deterministic output
collect_modules > "$MODULES_FILE"
awk -F: '
  !($1 in data) { order[++n] = $1 }
  { data[$1] = $0 }
  END { for (i = 1; i <= n; i++) print data[order[i]] }
' "$MODULES_FILE" > "$MODULES_FILE.tmp"
sort -o "$MODULES_FILE" "$MODULES_FILE.tmp"
rm -f "$MODULES_FILE.tmp"

case "$TARGET" in
  bash) emit_bash ;;
  *) emit_zsh ;;
esac