#!/usr/bin/env sh

origin=$(git remote get-url origin | sed -E "s|^.*\.com:(.*)\..*$|\1|g")
GITHUB_REPOSITORY=${GITHUB_REPOSITORY:-"${origin}"}
# full describe: exact tag on release builds (pj update string-matches it),
# distance+sha on dev builds (always differs from a release tag, so update
# correctly offers the latest release). No --dirty: it would break the
# equality check for tagged releases built from a dirty tree.
export VERSION=$(git describe --tags 2>/dev/null)
export SCRIPT_URL="https://github.com/${GITHUB_REPOSITORY}"

_update_template(){
  template_file="$1"; shift;

  for opt in $@; do
    key=$(echo "$opt" | sed -E "s/(\w+):.*$/\\\{\\\{\1\\\}\\\}/g");
    val=$(echo "$opt" | sed -E "s/\w+:(.*$)/\1/g");
    sed -E "s|${key}|${val}|g" -i $template_file
  done
}

_build(){
   # build-time identity stamp consumed by src/about.sh
   cat > src/about.local.sh <<EOF_ABOUT
# generated by bin/build.sh - do not commit
FRAMEWORK_REPOSITORY="$SCRIPT_URL"
FRAMEWORK_HOMEPAGE="$SCRIPT_URL"
EOF_ABOUT
   tar --exclude="./package.json" --exclude="./bun.lock" --exclude="./yarn.lock" --exclude="./node_modules" --exclude="./install.sh" -Jcf pj.tar.xz ./*
   cp assets/installer.sh install.sh
   _update_template "./install.sh" "version:$VERSION" "url:$SCRIPT_URL"
   # bundle the io library so the installer shares the framework UI;
   # regenerate from src/utils on every build, so the two cannot drift
   {
     printf '\n# -- bundled io library (generated by bin/build.sh; edit src/utils/{colors,io}.sh) --\n'
     cat src/utils/colors.sh
     cat src/utils/io.sh
     printf '# -- end bundled io library --\n\n'
   } >> "./install.sh"
   echo "SOURCE=\$(cat <<EOF" >> "./install.sh"
    base64 "./pj.tar.xz" >> "./install.sh"
   cat >> "./install.sh" <<END
EOF
)

_main \$@
END

    rm -rf pj.tar.xz
}

_build
